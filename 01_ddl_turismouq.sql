SET ECHO OFF
SET FEEDBACK ON

/* ---------------------------------------------------------------------
   Sección 0. Limpieza
   Borra las tablas en orden inverso de dependencias. Si una tabla no
   existe (ORA-00942) se ignora el error; cualquier otro error se propaga.
   --------------------------------------------------------------------- */
DECLARE
   TYPE t_lista IS TABLE OF VARCHAR2(30);
   v_tablas t_lista := t_lista(
      'USUARIO_SISTEMA', 'ROL',
      'RESENA', 'PAGO', 'RESERVA_SERVICIO', 'RESERVA_HABITACION', 'RESERVA',
      'CLIENTE', 'TARIFA', 'CALENDARIO', 'TEMPORADA',
      'SERVICIO', 'HABITACION', 'ALOJAMIENTO',
      'TIPO_ALOJAMIENTO', 'MUNICIPIO');
BEGIN
   FOR i IN 1 .. v_tablas.COUNT LOOP
      BEGIN
         EXECUTE IMMEDIATE 'DROP TABLE ' || v_tablas(i) || ' CASCADE CONSTRAINTS PURGE';
         DBMS_OUTPUT.PUT_LINE('Tabla eliminada: ' || v_tablas(i));
      EXCEPTION
         WHEN OTHERS THEN
            IF SQLCODE <> -942 THEN RAISE; END IF;
      END;
   END LOOP;
END;
/

/* =====================================================================
   Sección 1. Catálogos
