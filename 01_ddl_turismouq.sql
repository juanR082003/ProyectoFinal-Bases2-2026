-- MUNICIPIO: los 12 municipios del Quindío. Catálogo cerrado, por eso
-- la PK es un número asignado (no identidad) y el código DANE es único.
CREATE TABLE municipio (
   id_municipio   NUMBER(2)      NOT NULL,
   codigo_dane    CHAR(5)        NOT NULL,
   nombre         VARCHAR2(40)   NOT NULL,
   CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
   CONSTRAINT uq_municipio_dane   UNIQUE (codigo_dane),
   CONSTRAINT uq_municipio_nombre UNIQUE (nombre),
   CONSTRAINT ck_municipio_dane   CHECK (codigo_dane LIKE '63___')  -- 63 = Quindío
);

-- TIPO_ALOJAMIENTO: finca cafetera, hotel, glamping, hostal, ecohotel...
CREATE TABLE tipo_alojamiento (
   id_tipo        NUMBER(2)      NOT NULL,
   nombre         VARCHAR2(30)   NOT NULL,
   descripcion    VARCHAR2(250),
   CONSTRAINT pk_tipo_alojamiento PRIMARY KEY (id_tipo),
   CONSTRAINT uq_tipo_aloj_nombre UNIQUE (nombre)
);

/* =====================================================================
   Sección 2. Oferta: alojamientos, habitaciones y servicios
   ===================================================================== */

CREATE TABLE alojamiento (
   id_alojamiento   NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
   id_municipio     NUMBER(2)      NOT NULL,
   id_tipo          NUMBER(2)      NOT NULL,
   nombre_comercial VARCHAR2(80)   NOT NULL,
   nit              VARCHAR2(15)   NOT NULL,
   direccion        VARCHAR2(120)  NOT NULL,
   estrellas        NUMBER(1)      NOT NULL,   -- autoasignadas por el alojamiento
   telefono         VARCHAR2(20)   NOT NULL,
   correo           VARCHAR2(100)  NOT NULL,
   sitio_web        VARCHAR2(120),
   fecha_registro   DATE           DEFAULT SYSDATE NOT NULL,
   activo           CHAR(1)        DEFAULT 'S' NOT NULL,
   CONSTRAINT pk_alojamiento          PRIMARY KEY (id_alojamiento),
   CONSTRAINT fk_alojamiento_municipio FOREIGN KEY (id_municipio)
                                       REFERENCES municipio (id_municipio),
   CONSTRAINT fk_alojamiento_tipo      FOREIGN KEY (id_tipo)
                                       REFERENCES tipo_alojamiento (id_tipo),
   CONSTRAINT uq_alojamiento_nit       UNIQUE (nit),
   CONSTRAINT uq_alojamiento_correo    UNIQUE (correo),
   CONSTRAINT uq_alojamiento_nombre    UNIQUE (id_municipio, nombre_comercial),
   CONSTRAINT ck_alojamiento_estrellas CHECK (estrellas BETWEEN 1 AND 5),
   CONSTRAINT ck_alojamiento_correo    CHECK (correo LIKE '%_@_%._%'),
   CONSTRAINT ck_alojamiento_activo    CHECK (activo IN ('S','N'))
);

CREATE TABLE habitacion (
   id_habitacion    NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
   id_alojamiento   NUMBER(6)      NOT NULL,
   numero           VARCHAR2(10)   NOT NULL,
   tipo_habitacion  VARCHAR2(10)   NOT NULL,
   capacidad_max    NUMBER(2)      NOT NULL,
   descripcion      VARCHAR2(250),
   activa           CHAR(1)        DEFAULT 'S' NOT NULL,
   CONSTRAINT pk_habitacion             PRIMARY KEY (id_habitacion),
   CONSTRAINT fk_habitacion_alojamiento FOREIGN KEY (id_alojamiento)
                                        REFERENCES alojamiento (id_alojamiento),
   -- Dos habitaciones del mismo alojamiento no comparten número
   CONSTRAINT uq_habitacion_numero      UNIQUE (id_alojamiento, numero),
   -- Clave candidata (id, alojamiento) para las FK compuestas de RESERVA_HABITACION
   CONSTRAINT uq_habitacion_aloj        UNIQUE (id_habitacion, id_alojamiento),
   CONSTRAINT ck_habitacion_tipo        CHECK (tipo_habitacion IN ('SENCILLA','DOBLE','SUITE','CABANA')),
   CONSTRAINT ck_habitacion_capacidad   CHECK (capacidad_max BETWEEN 1 AND 12),
   -- Regla: una habitación sencilla no aloja más de 2 personas
   CONSTRAINT ck_habitacion_sencilla    CHECK (tipo_habitacion <> 'SENCILLA' OR capacidad_max <= 2),
   CONSTRAINT ck_habitacion_activa      CHECK (activa IN ('S','N'))
);

-- SERVICIO: cada servicio pertenece a UN alojamiento. El "Desayuno" del
-- hotel X y el del hotel Y son filas distintas, con precio propio.
CREATE TABLE servicio (
   id_servicio      NUMBER(5) GENERATED BY DEFAULT AS IDENTITY,
   id_alojamiento   NUMBER(6)      NOT NULL,
   nombre           VARCHAR2(60)   NOT NULL,
   descripcion      VARCHAR2(250),
   precio           NUMBER(10,2)   NOT NULL,
   unidad_cobro     VARCHAR2(12)   NOT NULL,
   activo           CHAR(1)        DEFAULT 'S' NOT NULL,
   CONSTRAINT pk_servicio             PRIMARY KEY (id_servicio),
   CONSTRAINT fk_servicio_alojamiento FOREIGN KEY (id_alojamiento)
                                      REFERENCES alojamiento (id_alojamiento),
   CONSTRAINT uq_servicio_nombre      UNIQUE (id_alojamiento, nombre),
   CONSTRAINT uq_servicio_aloj        UNIQUE (id_servicio, id_alojamiento),
   CONSTRAINT ck_servicio_precio      CHECK (precio > 0),
   CONSTRAINT ck_servicio_unidad      CHECK (unidad_cobro IN ('POR_PERSONA','POR_SERVICIO','POR_DIA')),
   CONSTRAINT ck_servicio_activo      CHECK (activo IN ('S','N'))
);

/* =====================================================================
   Sección 3. Temporadas, calendario y tarifas
   ===================================================================== */

-- TEMPORADA: un tramo de fechas con categoría ALTA/MEDIA/BAJA.
-- Es una instancia por año: "Semana Santa 2025" <> "Semana Santa 2026".
-- fecha_inicio y fecha_fin son INCLUSIVAS y se refieren a noches.
CREATE TABLE temporada (
   id_temporada     NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
   nombre           VARCHAR2(70)   NOT NULL,
   categoria        VARCHAR2(5)    NOT NULL,
   anio             NUMBER(4)      NOT NULL,
   fecha_inicio     DATE           NOT NULL,
   fecha_fin        DATE           NOT NULL,
   CONSTRAINT pk_temporada           PRIMARY KEY (id_temporada),
   CONSTRAINT uq_temporada_nombre    UNIQUE (nombre),
   CONSTRAINT uq_temporada_inicio    UNIQUE (fecha_inicio),
   CONSTRAINT ck_temporada_categoria CHECK (categoria IN ('ALTA','MEDIA','BAJA')),
   CONSTRAINT ck_temporada_rango     CHECK (fecha_fin >= fecha_inicio),
   CONSTRAINT ck_temporada_anio      CHECK (anio = EXTRACT(YEAR FROM fecha_inicio)),
   CONSTRAINT ck_temporada_sin_hora  CHECK (fecha_inicio = TRUNC(fecha_inicio)
                                            AND fecha_fin = TRUNC(fecha_fin))
);

-- CALENDARIO (entidad agregada): una fila por día. Su PK es la fecha y
-- cada fecha apunta a UNA sola temporada; así se garantiza de forma
-- declarativa que dos temporadas no se solapan y que no quedan huecos
-- en el rango cargado. Es la pieza que permite valorar una estadía
-- noche por noche (decisión de diseño 2).
CREATE TABLE calendario (
   fecha            DATE           NOT NULL,
   id_temporada     NUMBER(4)      NOT NULL,
   es_festivo       CHAR(1)        DEFAULT 'N' NOT NULL,
   anio             NUMBER(4)  GENERATED ALWAYS AS (EXTRACT(YEAR  FROM fecha)) VIRTUAL,
   mes              NUMBER(2)  GENERATED ALWAYS AS (EXTRACT(MONTH FROM fecha)) VIRTUAL,
   -- 1 = lunes ... 7 = domingo (el 01-01-1900 fue lunes); no depende de NLS
   dia_semana       NUMBER(1)  GENERATED ALWAYS AS (MOD(fecha - DATE '1900-01-01', 7) + 1) VIRTUAL,
   CONSTRAINT pk_calendario           PRIMARY KEY (fecha),
   CONSTRAINT fk_calendario_temporada FOREIGN KEY (id_temporada)
                                      REFERENCES temporada (id_temporada),
   CONSTRAINT ck_calendario_sin_hora  CHECK (fecha = TRUNC(fecha)),
   CONSTRAINT ck_calendario_festivo   CHECK (es_festivo IN ('S','N'))
);

-- TARIFA: precio por noche de una habitación en una temporada concreta.
-- No es un porcentaje fijo: cada alojamiento decide cuánto sube.
CREATE TABLE tarifa (
   id_tarifa           NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
   id_habitacion       NUMBER(6)      NOT NULL,
   id_temporada        NUMBER(4)      NOT NULL,
   valor_noche         NUMBER(10,2)   NOT NULL,
   fecha_actualizacion DATE           DEFAULT SYSDATE NOT NULL,
   CONSTRAINT pk_tarifa             PRIMARY KEY (id_tarifa),
   CONSTRAINT fk_tarifa_habitacion  FOREIGN KEY (id_habitacion)
                                    REFERENCES habitacion (id_habitacion),
   CONSTRAINT fk_tarifa_temporada   FOREIGN KEY (id_temporada)
                                    REFERENCES temporada (id_temporada),
   -- Una sola tarifa por habitación y temporada
   CONSTRAINT uq_tarifa_hab_temp    UNIQUE (id_habitacion, id_temporada),
   CONSTRAINT ck_tarifa_valor       CHECK (valor_noche > 0)
);

/* =====================================================================
   Sección 4. Clientes, reservas, pagos y reseñas
   ===================================================================== */

CREATE TABLE cliente (
   id_cliente        NUMBER(7) GENERATED BY DEFAULT AS IDENTITY,
   tipo_documento    VARCHAR2(3)    NOT NULL,
   numero_documento  VARCHAR2(20)   NOT NULL,
   nombres           VARCHAR2(60)   NOT NULL,
   apellidos         VARCHAR2(60)   NOT NULL,
   correo            VARCHAR2(120)  NOT NULL,
   telefono          VARCHAR2(20)   NOT NULL,
   ciudad_origen     VARCHAR2(60)   NOT NULL,
   pais_origen       VARCHAR2(40)   DEFAULT 'Colombia' NOT NULL,
   fecha_registro    DATE           DEFAULT SYSDATE NOT NULL,
   CONSTRAINT pk_cliente            PRIMARY KEY (id_cliente),
   CONSTRAINT uq_cliente_documento  UNIQUE (tipo_documento, numero_documento),
   CONSTRAINT uq_cliente_correo     UNIQUE (correo),
   -- Sin TI: el titular de una reserva debe ser mayor de edad
   CONSTRAINT ck_cliente_tipo_doc   CHECK (tipo_documento IN ('CC','CE','PA','PPT')),
   CONSTRAINT ck_cliente_correo     CHECK (correo LIKE '%_@_%._%')
);

-- RESERVA: encabezado. Pertenece a un cliente y a UN alojamiento; las
-- habitaciones van en RESERVA_HABITACION (decisión de diseño 1).
-- fecha_checkin / fecha_checkout es el rango GENERAL de la reserva.
CREATE TABLE reserva (
   id_reserva         NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
   id_cliente         NUMBER(7)      NOT NULL,
   id_alojamiento     NUMBER(6)      NOT NULL,
   fecha_reserva      DATE           DEFAULT SYSDATE NOT NULL,
   fecha_checkin      DATE           NOT NULL,
   fecha_checkout     DATE           NOT NULL,
   estado             VARCHAR2(10)   DEFAULT 'PENDIENTE' NOT NULL,
   fecha_cancelacion  DATE,
   observaciones      VARCHAR2(300),
   CONSTRAINT pk_reserva             PRIMARY KEY (id_reserva),
   CONSTRAINT fk_reserva_cliente     FOREIGN KEY (id_cliente)
                                     REFERENCES cliente (id_cliente),
   CONSTRAINT fk_reserva_alojamiento FOREIGN KEY (id_alojamiento)
                                     REFERENCES alojamiento (id_alojamiento),
   -- Claves candidatas para las FK compuestas de las tablas hijas
   CONSTRAINT uq_reserva_aloj        UNIQUE (id_reserva, id_alojamiento),
   CONSTRAINT uq_reserva_estado      UNIQUE (id_reserva, estado),
   CONSTRAINT ck_reserva_estado      CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA')),
   CONSTRAINT ck_reserva_fechas      CHECK (fecha_checkout > fecha_checkin),
   CONSTRAINT ck_reserva_max_noches  CHECK (fecha_checkout - fecha_checkin <= 30),
   CONSTRAINT ck_reserva_sin_hora    CHECK (fecha_checkin = TRUNC(fecha_checkin)
                                            AND fecha_checkout = TRUNC(fecha_checkout)),
   -- No se reserva hacia atrás: la reserva se hace antes (o el mismo día) del check-in
   CONSTRAINT ck_reserva_anticipada  CHECK (TRUNC(fecha_reserva) <= fecha_checkin),
   -- fecha_cancelacion existe si y solo si la reserva está cancelada,
   -- y la cancelación ocurre entre la reserva y el check-in
   CONSTRAINT ck_reserva_cancelacion CHECK (
         (estado =  'CANCELADA' AND fecha_cancelacion IS NOT NULL
                                AND fecha_cancelacion >= fecha_reserva
                                AND TRUNC(fecha_cancelacion) <= fecha_checkin)
      OR (estado <> 'CANCELADA' AND fecha_cancelacion IS NULL))
);

-- RESERVA_HABITACION: líneas de la reserva. Cada línea tiene sus propias
-- fechas (alguien del grupo puede llegar un día después) y guarda el
-- valor de la estadía calculado noche por noche al momento de reservar.
CREATE TABLE reserva_habitacion (
   id_reserva_habitacion NUMBER(9) GENERATED BY DEFAULT AS IDENTITY,
   id_reserva            NUMBER(8)      NOT NULL,
   id_alojamiento        NUMBER(6)      NOT NULL,
   id_habitacion         NUMBER(6)      NOT NULL,
   fecha_checkin         DATE           NOT NULL,
   fecha_checkout        DATE           NOT NULL,
   num_huespedes         NUMBER(2)      NOT NULL,
   valor_estadia         NUMBER(12,2)   NOT NULL,
   CONSTRAINT pk_reserva_habitacion  PRIMARY KEY (id_reserva_habitacion),
   -- FK compuesta: la línea es del mismo alojamiento que la reserva...
   CONSTRAINT fk_rh_reserva          FOREIGN KEY (id_reserva, id_alojamiento)
                                     REFERENCES reserva (id_reserva, id_alojamiento),
   -- ...y la habitación pertenece a ese mismo alojamiento
   CONSTRAINT fk_rh_habitacion       FOREIGN KEY (id_habitacion, id_alojamiento)
                                     REFERENCES habitacion (id_habitacion, id_alojamiento),
   CONSTRAINT uq_rh_reserva_hab      UNIQUE (id_reserva, id_habitacion),
   CONSTRAINT ck_rh_fechas           CHECK (fecha_checkout > fecha_checkin),
   CONSTRAINT ck_rh_sin_hora         CHECK (fecha_checkin = TRUNC(fecha_checkin)
                                            AND fecha_checkout = TRUNC(fecha_checkout)),
   CONSTRAINT ck_rh_huespedes        CHECK (num_huespedes > 0),
   CONSTRAINT ck_rh_valor            CHECK (valor_estadia >= 0)
);

-- RESERVA_SERVICIO: servicios complementarios contratados en la reserva.
-- Guarda el precio unitario vigente al contratar (histórico de precios).
CREATE TABLE reserva_servicio (
   id_reserva_servicio  NUMBER(9) GENERATED BY DEFAULT AS IDENTITY,
   id_reserva           NUMBER(8)      NOT NULL,
   id_alojamiento       NUMBER(6)      NOT NULL,
   id_servicio          NUMBER(5)      NOT NULL,
   fecha_servicio       DATE           NOT NULL,
   cantidad             NUMBER(3)      NOT NULL,
   precio_unitario      NUMBER(10,2)   NOT NULL,
   subtotal             NUMBER(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) VIRTUAL,
   CONSTRAINT pk_reserva_servicio   PRIMARY KEY (id_reserva_servicio),
   CONSTRAINT fk_rs_reserva         FOREIGN KEY (id_reserva, id_alojamiento)
                                    REFERENCES reserva (id_reserva, id_alojamiento),
   -- El servicio debe ser del mismo alojamiento de la reserva
   CONSTRAINT fk_rs_servicio        FOREIGN KEY (id_servicio, id_alojamiento)
                                    REFERENCES servicio (id_servicio, id_alojamiento),
   CONSTRAINT uq_rs_linea           UNIQUE (id_reserva, id_servicio, fecha_servicio),
   CONSTRAINT ck_rs_cantidad        CHECK (cantidad BETWEEN 1 AND 50),
   CONSTRAINT ck_rs_precio          CHECK (precio_unitario > 0),
   CONSTRAINT ck_rs_sin_hora        CHECK (fecha_servicio = TRUNC(fecha_servicio))
);

-- PAGO: una reserva puede tener varios pagos (anticipo + saldo, reintentos
-- fallidos). Un reembolso no se borra: el pago pasa a REEMBOLSADO y se
-- registra cuánto se devolvió (80 % si se canceló con > 5 días).
CREATE TABLE pago (
   id_pago            NUMBER(9) GENERATED BY DEFAULT AS IDENTITY,
   id_reserva         NUMBER(8)      NOT NULL,
   fecha_pago         DATE           NOT NULL,
   monto              NUMBER(12,2)   NOT NULL,
   metodo             VARCHAR2(16)   NOT NULL,
   estado             VARCHAR2(11)   NOT NULL,
   concepto           VARCHAR2(8)    NOT NULL,
   monto_reembolsado  NUMBER(12,2)   DEFAULT 0 NOT NULL,
   fecha_reembolso    DATE,
   referencia         VARCHAR2(30),
   CONSTRAINT pk_pago              PRIMARY KEY (id_pago),
   CONSTRAINT fk_pago_reserva      FOREIGN KEY (id_reserva)
                                   REFERENCES reserva (id_reserva),
   CONSTRAINT uq_pago_referencia   UNIQUE (referencia),
   CONSTRAINT ck_pago_monto        CHECK (monto > 0),
   CONSTRAINT ck_pago_metodo       CHECK (metodo IN ('TARJETA_CREDITO','TARJETA_DEBITO','PSE','TRANSFERENCIA','EFECTIVO')),
   CONSTRAINT ck_pago_estado       CHECK (estado IN ('EXITOSO','FALLIDO','PENDIENTE','REEMBOLSADO')),
   CONSTRAINT ck_pago_concepto     CHECK (concepto IN ('ANTICIPO','SALDO','TOTAL')),
   CONSTRAINT ck_pago_reembolso_rango CHECK (monto_reembolsado BETWEEN 0 AND monto),
   -- Solo un pago REEMBOLSADO tiene monto y fecha de reembolso
   CONSTRAINT ck_pago_reembolso    CHECK (
         (estado =  'REEMBOLSADO' AND monto_reembolsado > 0
                                  AND fecha_reembolso IS NOT NULL
                                  AND fecha_reembolso >= fecha_pago)
      OR (estado <> 'REEMBOLSADO' AND monto_reembolsado = 0 AND fecha_reembolso IS NULL)),
   -- El efectivo no tiene referencia electrónica; los demás métodos sí
   CONSTRAINT ck_pago_referencia   CHECK (
         (metodo =  'EFECTIVO' AND referencia IS NULL)
      OR (metodo <> 'EFECTIVO' AND referencia IS NOT NULL))
);

-- RESENA: una reseña por reserva. La FK compuesta (id_reserva,
-- estado_reserva) apunta a (id_reserva, estado) de RESERVA y
-- estado_reserva solo puede valer 'COMPLETADA': así el motor rechaza
-- reseñas de reservas canceladas, pendientes o confirmadas, y además
-- impide cambiar el estado de una reserva que ya fue reseñada.
CREATE TABLE resena (
   id_resena        NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
   id_reserva       NUMBER(8)      NOT NULL,
   estado_reserva   VARCHAR2(10)   DEFAULT 'COMPLETADA' NOT NULL,
   calificacion     NUMBER(1)      NOT NULL,
   comentario       VARCHAR2(500),
   fecha_resena     DATE           DEFAULT SYSDATE NOT NULL,
   CONSTRAINT pk_resena              PRIMARY KEY (id_resena),
   CONSTRAINT fk_resena_reserva      FOREIGN KEY (id_reserva, estado_reserva)
                                     REFERENCES reserva (id_reserva, estado),
   CONSTRAINT uq_resena_reserva      UNIQUE (id_reserva),
   CONSTRAINT ck_resena_estado       CHECK (estado_reserva = 'COMPLETADA'),
   CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5)
);

/* =====================================================================
   Sección 5. Usuarios internos de la plataforma
   ===================================================================== */

-- ROL (entidad agregada): catálogo de roles de la aplicación. El ámbito
-- dice si el rol opera sobre toda la plataforma o sobre un alojamiento.
CREATE TABLE rol (
   id_rol        NUMBER(2)      NOT NULL,
   nombre        VARCHAR2(30)   NOT NULL,
   ambito        VARCHAR2(11)   NOT NULL,
   descripcion   VARCHAR2(250),
   CONSTRAINT pk_rol          PRIMARY KEY (id_rol),
   CONSTRAINT uq_rol_nombre   UNIQUE (nombre),
   CONSTRAINT uq_rol_ambito   UNIQUE (id_rol, ambito),
   CONSTRAINT ck_rol_ambito   CHECK (ambito IN ('PLATAFORMA','ALOJAMIENTO'))
);

CREATE TABLE usuario_sistema (
   id_usuario       NUMBER(5) GENERATED BY DEFAULT AS IDENTITY,
   username         VARCHAR2(30)   NOT NULL,
   nombre_completo  VARCHAR2(100)  NOT NULL,
   correo           VARCHAR2(120)  NOT NULL,
   id_rol           NUMBER(2)      NOT NULL,
   ambito_rol       VARCHAR2(11)   NOT NULL,
   id_alojamiento   NUMBER(6),
   activo           CHAR(1)        DEFAULT 'S' NOT NULL,
   fecha_creacion   DATE           DEFAULT SYSDATE NOT NULL,
   ultimo_acceso    DATE,
   CONSTRAINT pk_usuario_sistema   PRIMARY KEY (id_usuario),
   CONSTRAINT fk_usuario_rol       FOREIGN KEY (id_rol, ambito_rol)
                                   REFERENCES rol (id_rol, ambito),
   CONSTRAINT fk_usuario_aloj      FOREIGN KEY (id_alojamiento)
                                   REFERENCES alojamiento (id_alojamiento),
   CONSTRAINT uq_usuario_username  UNIQUE (username),
   CONSTRAINT uq_usuario_correo    UNIQUE (correo),
   CONSTRAINT ck_usuario_username  CHECK (username = LOWER(username)),
   CONSTRAINT ck_usuario_activo    CHECK (activo IN ('S','N')),
   -- Un rol de alojamiento exige alojamiento; uno de plataforma lo prohíbe
   CONSTRAINT ck_usuario_ambito    CHECK (
         (ambito_rol = 'ALOJAMIENTO' AND id_alojamiento IS NOT NULL)
      OR (ambito_rol = 'PLATAFORMA'  AND id_alojamiento IS NULL))
);

/* =====================================================================
   Sección 6. Comentarios del diccionario de datos
