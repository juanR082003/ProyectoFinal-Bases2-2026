   TurismoUQ · Proyecto integrador Bases de Datos II · 2026-2
   Script 01 · Modelo físico (DDL)
   ---------------------------------------------------------------------
   Motor   : Oracle Database XE 21c
   Esquema : TURISMOUQ (creado con 00_crear_usuario.sql)
   Orden   : 00 -> 01 (este) -> 02 carga -> 03 consultas

   Contenido
     Sección 0. Limpieza: borra las tablas si existen (base limpia).
     Sección 1. Catálogos geográficos y de tipos (MUNICIPIO, TIPO_ALOJAMIENTO).
     Sección 2. Oferta: ALOJAMIENTO, HABITACION, SERVICIO.
     Sección 3. Precios: TEMPORADA, CALENDARIO (entidad agregada), TARIFA.
     Sección 4. Demanda: CLIENTE, RESERVA, RESERVA_HABITACION,
                RESERVA_SERVICIO, PAGO, RESENA.
     Sección 5. Usuarios internos: ROL (entidad agregada), USUARIO_SISTEMA.
     Sección 6. Comentarios de tablas y columnas clave.

   Convenciones
     pk_  clave primaria      fk_  clave foránea
     uq_  única               ck_  CHECK
     Todas las fechas de estadía (check-in, check-out, noches) se guardan
     sin hora (TRUNC). Una "noche" se identifica por la fecha en que
     empieza: la estadía 20-dic -> 23-dic tiene las noches 20, 21 y 22.

   Patrón de diseño usado varias veces: FK COMPUESTA hacia una clave
   única (id, atributo) del padre. Permite validar de forma declarativa
   reglas que cruzan dos tablas, sin disparadores:
     - RESERVA_HABITACION -> la habitación es del mismo alojamiento
       de la reserva.
     - RESERVA_SERVICIO   -> el servicio es del mismo alojamiento
       de la reserva.
     - RESENA             -> solo se reseñan reservas COMPLETADAS.
     - USUARIO_SISTEMA    -> los roles de alojamiento exigen alojamiento.
   ===================================================================== */

